if (isset($_POST['evaluate_kpi'])) {
    $assessment_id = $_POST['assessment_id'];
    $kpi_effectiveness = intval($_POST['kpi_effectiveness']);
    $kpi_efficiency = intval($_POST['kpi_efficiency']);
    $kpi_relevance = intval($_POST['kpi_relevance']);
    $kpi_sustainability = intval($_POST['kpi_sustainability']);
    $kpi_equity = intval($_POST['kpi_equity']);
    
    // Calculate impact percentage (weighted average)
    $total_weight = 5;
    $weighted_score = ($kpi_effectiveness + $kpi_efficiency + $kpi_relevance + $kpi_sustainability + $kpi_equity);
    $impact_percentage = round(($weighted_score / ($total_weight * 100)) * 100);
    
    // Determine impact rating based on percentage
    if ($impact_percentage >= 80) {
        $impact_rating = 'High';
        $workflow_action = 'Proceed to Benchmarking';
        $assessment_status = 'Approved for Benchmarking';
    } elseif ($impact_percentage >= 60) {
        $impact_rating = 'Moderate';
        $workflow_action = 'Proceed to Benchmarking';
        $assessment_status = 'Approved for Benchmarking';
    } elseif ($impact_percentage >= 40) {
        $impact_rating = 'Low';
        $workflow_action = 'Archived';
        $assessment_status = 'Archived - Low Impact';
    } else {
        $impact_rating = 'Very Low';
        $workflow_action = 'Archived';
        $assessment_status = 'Archived - Very Low Impact';
    }
    
    // Update assessment with KPI evaluation results
    $update_sql = "UPDATE impact_assessments SET 
                   kpi_effectiveness = '$kpi_effectiveness',
                   kpi_efficiency = '$kpi_efficiency',
                   kpi_relevance = '$kpi_relevance',
                   kpi_sustainability = '$kpi_sustainability',
                   kpi_equity = '$kpi_equity',
                   impact_percentage = '$impact_percentage',
                   impact_rating = '$impact_rating',
                   kpi_evaluated = 'Yes',
                   kpi_evaluation_date = NOW(),
                   workflow_action = '$workflow_action',
                   assessment_status = '$assessment_status',
                   updated_by = '$username',
                   updated_date = NOW()
                   WHERE assessment_id = '$assessment_id'";
    
    if ($conn->query($update_sql) === TRUE) {
        $log_sql = "INSERT INTO activity_logs (user, action, document_id, module, timestamp) 
                    VALUES ('$username', 'KPI Evaluation completed. Impact: $impact_percentage% ($impact_rating) - $workflow_action', '$assessment_id', 'Impact Assessment', NOW())";
