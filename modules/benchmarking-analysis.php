    }
    $benchmark_id = $_POST['benchmark_id'];
    
    // Comparison Matrix Criteria - 10 criteria (1-10 scale)
    $criteria1 = intval($_POST['criteria1']);
    $criteria2 = intval($_POST['criteria2']);
    $criteria3 = intval($_POST['criteria3']);
    $criteria4 = intval($_POST['criteria4']);
    $criteria5 = intval($_POST['criteria5']);
    $criteria6 = intval($_POST['criteria6']);
    $criteria7 = intval($_POST['criteria7']);
    $criteria8 = intval($_POST['criteria8']);
    $criteria9 = intval($_POST['criteria9']);
    $criteria10 = intval($_POST['criteria10']);
    $comments = $conn->real_escape_string($_POST['comments']);
    
    // Calculate total and average (out of 10)
    $total = $criteria1 + $criteria2 + $criteria3 + $criteria4 + $criteria5 + 
             $criteria6 + $criteria7 + $criteria8 + $criteria9 + $criteria10;
    $average = round($total / 10, 1);
    
    // Determine overall rating based on 10-point scale
    if ($average >= 9.0) $rating = 'Excellent';
    elseif ($average >= 7.5) $rating = 'Good';
    elseif ($average >= 6.0) $rating = 'Fair';
    elseif ($average >= 4.0) $rating = 'Poor';
    else $rating = 'Very Poor';
    
    // Determine recommendation based on 10-point scale
    if ($average >= 8.0) {
        $recommendation = 'Strongly Recommend for Adoption';
    } elseif ($average >= 6.5) {
        $recommendation = 'Recommend with Amendments';
    } elseif ($average >= 4.5) {
        $recommendation = 'Needs Significant Revision';
    } else {
        $recommendation = 'Not Recommended';
    }
    
    // Check if exists
    $check_sql = "SELECT * FROM benchmarking_matrix WHERE benchmark_id = '$benchmark_id'";
    $check_result = $conn->query($check_sql);
    
    if ($check_result && $check_result->num_rows > 0) {
        // Update
        $update_sql = "UPDATE benchmarking_matrix SET 
                       criteria1 = '$criteria1', criteria2 = '$criteria2', criteria3 = '$criteria3',
                       criteria4 = '$criteria4', criteria5 = '$criteria5', criteria6 = '$criteria6',
                       criteria7 = '$criteria7', criteria8 = '$criteria8', criteria9 = '$criteria9',
                       criteria10 = '$criteria10',
                       average_score = '$average', rating = '$rating', 
                       recommendation = '$recommendation',
                       comments = '$comments',
                       evaluated_by = '$username', evaluated_date = NOW()
                       WHERE benchmark_id = '$benchmark_id'";
        $conn->query($update_sql);
    } else {
        // Insert
        $insert_sql = "INSERT INTO benchmarking_matrix 
                       (benchmark_id, criteria1, criteria2, criteria3, criteria4, criteria5, 
                        criteria6, criteria7, criteria8, criteria9, criteria10,
                        average_score, rating, recommendation, comments, evaluated_by, evaluated_date)
                       VALUES 
                       ('$benchmark_id', '$criteria1', '$criteria2', '$criteria3', '$criteria4', '$criteria5',
                        '$criteria6', '$criteria7', '$criteria8', '$criteria9', '$criteria10',
                        '$average', '$rating', '$recommendation', '$comments', '$username', NOW())";
        $conn->query($insert_sql);
    }
    
    // Update submission status
    $conn->query("UPDATE benchmarking_submissions SET status = 'Evaluated' WHERE benchmark_id = '$benchmark_id'");
    
    // Redirect to refresh
    header("Location: benchmarking-analysis.php?analyze=" . urlencode($benchmark_id) . "&matrix_saved=1");
    exit();
}
