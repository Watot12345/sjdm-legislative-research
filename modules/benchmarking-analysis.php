if (!function_exists('formatLegislativeDocumentHtml')) {
    function formatLegislativeDocumentHtml($content) {
        if (empty($content)) return '';

        // Strip duplicate summary header prefix if === LEGAL DOCUMENTS === marker is present
        if (strpos($content, '=== LEGAL DOCUMENTS ===') !== false) {
            $parts = explode('=== LEGAL DOCUMENTS ===', $content, 2);
            $content = trim($parts[1]);
        }

        $lines = explode("\n", $content);
        $html = '<div class="legislative-report-body space-y-4 text-slate-900 font-serif">';
        $in_doc_card = false;

        foreach ($lines as $line) {
            $trimmed = trim($line);

            if (empty($trimmed)) {
                continue;
            }

            // Match === MAIN TITLE / SECTION ===
            if (preg_match('/^===\s*(.*?)\s*===$/', $trimmed, $matches)) {
                if ($in_doc_card) {
                    $html .= '</div></div>';
                    $in_doc_card = false;
                }
                $title = htmlspecialchars($matches[1]);
                $html .= '<div class="my-4 pt-3 border-b-2 border-slate-900 pb-1.5"><h3 class="text-base font-bold uppercase tracking-wide text-slate-900 font-serif">' . $title . '</h3></div>';
            }
            // Match --- Document N: Title ---
            elseif (preg_match('/^---\s*Document\s*(\d+):\s*(.*?)\s*---$/', $trimmed, $matches)) {
                if ($in_doc_card) {
                    $html .= '</div></div>';
                }
                $doc_num = htmlspecialchars($matches[1]);
                $doc_title = htmlspecialchars($matches[2]);
                $in_doc_card = true;
                $html .= '<div class="legal-document-card bg-white p-4 rounded-lg border border-slate-300 shadow-sm my-3 print:border-slate-400 print:shadow-none"><div class="border-b border-slate-200 pb-2 mb-3"><h4 class="text-sm font-bold text-slate-900 font-serif"><i class="fa-solid fa-file-contract text-indigo-700 mr-2 no-print"></i>Document ' . $doc_num . ': ' . $doc_title . '</h4></div><div class="space-y-2">';
            }
            // Match Divider ---
            elseif (preg_match('/^-{10,}$/', $trimmed)) {
                if ($in_doc_card) {
                    $html .= '</div></div>';
                    $in_doc_card = false;
                }
            }
            // Match Metadata Lines
            elseif (preg_match('/^(Document ID|Generated By|Generated Date|Benchmark ID|Assessment ID|Policy Title|Department|Impact Rating|Impact Percentage|Effectiveness|Efficiency|Relevance|Sustainability|Equity|Implementation Rate|Budget Utilization|Beneficiaries):\s*(.*)$/', $trimmed, $matches)) {
                $key = htmlspecialchars($matches[1]);
                $val = htmlspecialchars($matches[2]);
                $html .= '<div class="text-xs text-slate-800 font-medium py-0.5"><span class="font-bold text-slate-900 font-sans">' . $key . ':</span> <span class="font-mono text-indigo-700">' . $val . '</span></div>';
            }
            // Normal paragraph text
            else {
                $html .= '<p class="text-[13px] leading-relaxed text-slate-800 text-justify mb-2 font-serif" style="text-indent: 1.25rem;">' . htmlspecialchars($trimmed) . '</p>';
            }
        }

        if ($in_doc_card) {
            $html .= '</div></div>';
        }

        $html .= '</div>';
        return $html;
    }
}

