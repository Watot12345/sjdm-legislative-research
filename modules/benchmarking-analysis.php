    // Client-side real-time table row filter
    function liveFilterTable(query) {
        const filter = query.toLowerCase();
        const rows = document.querySelectorAll('.submission-row, .dataset-row');
        rows.forEach(row => {
            const text = row.textContent.toLowerCase();
            row.style.display = text.includes(filter) ? '' : 'none';
        });
    }

    // Close analysis modal
    function closeAnalysisModal() {
        let modal = document.getElementById('analysisModal');
        if (modal) {
            modal.style.display = 'none';
        }
        if (window.history.replaceState) {
            const cleanUrl = window.location.protocol + "//" + window.location.host + window.location.pathname;
            window.history.replaceState({path: cleanUrl}, '', cleanUrl);
        } else {
            window.location.href = 'benchmarking-analysis.php';
        }
    }

    // Toggle matrix form visibility
    function toggleMatrixForm() {
        const form = document.getElementById('matrixForm');
        if (form) {
            form.classList.toggle('hidden');
        }
    }

    // Update rating selection
    function updateRating(radio) {
        const card = radio.closest('.criteria-card');
        if (!card) return;
        
        const numbers = card.querySelectorAll('.rating-number');
        const value = parseInt(radio.value);
        
        // Remove selected class from all numbers in this card
        numbers.forEach(num => num.classList.remove('selected'));
        
        // Add selected class to the matching number
        numbers.forEach(num => {
            if (parseInt(num.textContent) === value) {
                num.classList.add('selected');
            }
        });
        
        card.classList.add('selected');
    }

    // Handle number click - properly selects the right number
    function handleNumberClick(numberElement) {
        const card = numberElement.closest('.criteria-card');
        if (!card) return;
        
        const value = parseInt(numberElement.textContent);
        const radio = card.querySelector(`input[type="radio"][value="${value}"]`);
        
        if (radio) {
            radio.checked = true;
            // Remove selected class from all numbers
            const numbers = card.querySelectorAll('.rating-number');
            numbers.forEach(num => num.classList.remove('selected'));
            // Add selected class to clicked number
            numberElement.classList.add('selected');
            card.classList.add('selected');
            
            // Update the radio button's checked state visually
            const event = new Event('change', { bubbles: true });
            radio.dispatchEvent(event);
        }
    }

    // Download report
